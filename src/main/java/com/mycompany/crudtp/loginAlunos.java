    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        
        String sql = "SELECT * FROM tb_aluno " +
             "WHERE cd_rm_aluno = ? " +
             "AND email_aluno = ? " +
             "AND senha_aluno = ?";

        try (Connection conn = ConexaoBanco.conectar();
        PreparedStatement mensagem = conn.prepareStatement(sql)) {

        mensagem.setString(1, txtRmAluno.getText().trim());
        mensagem.setString(2, txtEmail.getText().trim());
        mensagem.setString(3, txtSenha.getText());

        try (ResultSet resultado = mensagem.executeQuery()) {

        if (resultado.next()) {
            JOptionPane.showMessageDialog(
                this, "Login realizado com sucesso!"
            );
            acessoSistema tela = new acessoSistema();
            tela.setVisible(true);
            this.dispose();

        } else {
            JOptionPane.showMessageDialog(
                this,
                "RM, e-mail ou senha incorretos!",
                "Erro no login",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
        this,
            "Erro ao consultar o banco: " + e.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE
    );
}

    }//GEN-LAST:event_btnConfirmarActionPerformed

