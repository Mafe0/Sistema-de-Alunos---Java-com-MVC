    private void limparCampos() {

        txtRM.setText("");
        txtNome.setText("");
        txtIdade.setText("");
        txtEmail.setText("");
        txtSenha.setText("");

        cdAlunoSelecionado = -1;

        tbAlunos.clearSelection();
    }

    private void carregarAlunos() {

    DefaultTableModel modelo = new DefaultTableModel(
        new Object[]{"Código", "RM", "Nome", "Idade", "E-mail"},
        0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    List<Aluno> alunos = controller.listarAlunos();

    for (Aluno aluno : alunos) {

        modelo.addRow(new Object[]{
            aluno.getCdAluno(),
            aluno.getRm(),
            aluno.getNome(),
            aluno.getIdade(),
            aluno.getEmail()
        });
    }

        tbAlunos.setModel(modelo);
    }   
    
    private void preencherCampos() {

    int linha = tbAlunos.getSelectedRow();

    if (linha >= 0) {

        cdAlunoSelecionado = Integer.parseInt(
            tbAlunos.getValueAt(linha, 0).toString()
        );

        String rm = tbAlunos.getValueAt(linha, 1).toString();
        String nome = tbAlunos.getValueAt(linha, 2).toString();
        String idade = tbAlunos.getValueAt(linha, 3).toString();
        String email = tbAlunos.getValueAt(linha, 4).toString();

        txtRM.setText(rm);
        txtNome.setText(nome);
        txtIdade.setText(idade);
        txtEmail.setText(email);

        // Busca a senha do aluno selecionado
        for (Aluno aluno : controller.listarAlunos()) {
            if (aluno.getCdAluno() == cdAlunoSelecionado) {
                txtSenha.setText(aluno.getSenha());
                break;
            }
        }
      }
    }
    
