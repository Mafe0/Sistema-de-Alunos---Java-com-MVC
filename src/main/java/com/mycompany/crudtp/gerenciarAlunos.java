    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (cdAlunoSelecionado == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um aluno!");
        return;
    }

    int resposta = JOptionPane.showConfirmDialog(
        this,
        "Deseja realmente excluir este aluno?",
        "Confirmar exclusão",
        JOptionPane.YES_NO_OPTION
    );

    if (resposta == JOptionPane.YES_OPTION) {

        try {

            boolean excluido = controller.deletarAluno(cdAlunoSelecionado);

            if (excluido) {
                JOptionPane.showMessageDialog(this, "Aluno excluído com sucesso!");
                carregarAlunos();
                limparCampos();
            } else {
                JOptionPane.showMessageDialog(this, "Não foi possível excluir o aluno.");
            }

        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, "Erro ao excluir: " + e.getMessage());
        }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        if (cdAlunoSelecionado == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um aluno!");
        return;
    }

    try {

        Aluno aluno = new Aluno();

        aluno.setCdAluno(cdAlunoSelecionado);
        aluno.setRm(txtRM.getText());
        aluno.setNome(txtNome.getText());
        aluno.setIdade(Integer.parseInt(txtIdade.getText()));
        aluno.setEmail(txtEmail.getText());
        aluno.setSenha(txtSenha.getText());

        boolean atualizado = controller.atualizarAluno(aluno);

        if (atualizado) {
            JOptionPane.showMessageDialog(this, "Aluno atualizado com sucesso!");
            carregarAlunos();
            limparCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Nenhum aluno foi atualizado.");
        }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Digite uma idade válida!");
        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAtualizarActionPerformed

