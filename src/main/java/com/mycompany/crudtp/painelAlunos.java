    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        // TODO add your handling code here:
       
        String cd_rm_aluno;
        String nm_aluno;
        int nr_idade_aluno;
        String email_aluno;
        String senha_aluno;
        
        cd_rm_aluno = txtRmAluno.getText();
        nm_aluno = txtNome.getText();
        nr_idade_aluno = Integer.parseInt(txtIdade.getText());
        email_aluno = txtEmail.getText();
        senha_aluno = txtSenha.getText();
        
        String sql = "INSERT INTO tb_aluno" + "(cd_rm_aluno, nm_aluno, nr_idade_aluno, email_aluno, senha_aluno)" + "VALUES (?, ?, ?, ?, ?)";
        
        try(Connection conn = ConexaoBanco.conectar();
            PreparedStatement mensagem = conn.prepareStatement(sql)) {
            
            mensagem.setString(1, cd_rm_aluno);
            mensagem.setString(2, nm_aluno);
            mensagem.setInt(3, nr_idade_aluno);
            mensagem.setString(4, email_aluno);
            mensagem.setString(5, senha_aluno);
            
            mensagem.executeUpdate();
            System.out.println("Aluno cadastrado com sucesso!");
            JOptionPane.showMessageDialog(null, "Aluno cadastrado com sucesso!");
            
        }catch(SQLException e){
            throw new RuntimeException("Erro ao conectar ao banco", e);
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

